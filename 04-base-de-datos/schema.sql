-- Modelo de pedidos. Motor: PostgreSQL 16.

CREATE TABLE addresses
(
    address_id INT  GENERATED BY DEFAULT AS IDENTITY,
    street VARCHAR(30) NOT NULL,
    number smallint NOT NULL,
    floor smallint,
    apartment char(1),
    city VARCHAR(30) NOT NULL,

    CONSTRAINT pk_address primary key(address_id),
    CONSTRAINT ck_address_apartment CHECK (apartment BETWEEN 'A' AND 'Z')
);

CREATE TABLE document_types(
                               document_type_id INT GENERATED BY DEFAULT AS IDENTITY,
                               name VARCHAR(30) NOT NULL,

                               CONSTRAINT pk_document_types primary key(document_type_id),
                               CONSTRAINT uq_document_type_name UNIQUE(name)
);

CREATE TABLE documents(
                          document_id INT GENERATED BY DEFAULT AS IDENTITY,
                          document_number VARCHAR(20) NOT NULL,
                          document_type_id INT NOT NULL,

                          CONSTRAINT pk_document PRIMARY KEY (document_id),
                          CONSTRAINT fk_documents_document_types FOREIGN KEY (document_type_id) REFERENCES document_types(document_type_id),
                          CONSTRAINT uq_document UNIQUE (document_type_id,document_number)

);

CREATE TABLE customers(
                          customer_id INT GENERATED BY DEFAULT AS IDENTITY,
                          first_name VARCHAR(30) NOT NULL,
                          last_name VARCHAR(30) NOT NULl,
                          email VARCHAR(50) NOT NULL,
                          phone VARCHAR(20) NOT NULL,
                          address_id INT NOT NULL,
                          document_id INT NOT NULL,

                          CONSTRAINT pk_customer PRIMARY KEY (customer_id),
                          CONSTRAINT fk_customers_addresses FOREIGN KEY (address_id) REFERENCES addresses(address_id),
                          CONSTRAINT fk_customers_documents FOREIGN KEY (document_id) REFERENCES documents(document_id) ,
                          CONSTRAINT ck_customer_email CHECK( email like ('%@%') ),
                          CONSTRAINT uq_customer_document UNIQUE(document_id),
                          CONSTRAINT uq_customer_address UNIQUE (address_id),
                          CONSTRAINT uq_customer_email UNIQUE (email)
);

CREATE TABLE order_statuses(
                               order_status_id INT GENERATED BY DEFAULT AS IDENTITY,
                               name VARCHAR(30) NOT NULL,

                               CONSTRAINT pk_order_status PRIMARY KEY (order_status_id),
                               CONSTRAINT uq_order_statuses_name UNIQUE(name)
);


CREATE TABLE orders(
                       order_id INT GENERATED BY DEFAULT AS IDENTITY,
                       order_date TIMESTAMP NOT NULL,
                       customer_id INT NOT NULL ,
                       order_status_id INT NOT NULL,

                       CONSTRAINT pk_order PRIMARY KEY(order_id),
                       CONSTRAINT fk_orders_customers FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
                       CONSTRAINT fk_orders_order_statuses FOREIGN KEY (order_status_id) REFERENCES order_statuses(order_status_id)
);

CREATE TABLE order_status_history(
                                     history_id INT GENERATED BY DEFAULT AS IDENTITY,
                                     changed_at TIMESTAMP NOT NULL,
                                     order_id INT NOT NULL,
                                     order_status_id INT NOT NULL,

                                     CONSTRAINT pk_order_status_history PRIMARY KEY(history_id),
                                     CONSTRAINT fk_history_order FOREIGN KEY (order_id) REFERENCES orders(order_id),
                                     CONSTRAINT fk_history_order_status FOREIGN KEY(order_status_id) REFERENCES order_statuses(order_status_id)
);

CREATE TABLE payment_statuses(
                                 payment_status_id INT GENERATED BY DEFAULT AS IDENTITY,
                                 name VARCHAR(30) NOT NULL,

                                 CONSTRAINT pk_payment_status PRIMARY KEY (payment_status_id),
                                 CONSTRAINT uq_payment_statuses_name UNIQUE(name)
);

CREATE TABLE payments(
                         payment_id INT GENERATED BY DEFAULT AS IDENTITY,
                         amount NUMERIC(12,2) NOT NULL,
                         payment_datetime TIMESTAMP NOT NULL ,
                         payment_status_id INT NOT NULL,
                         order_id INT NOT NULL,

                         CONSTRAINT pk_payment PRIMARY KEY(payment_id),
                         CONSTRAINT fk_payments_payment_statuses FOREIGN KEY(payment_status_id) REFERENCES payment_statuses(payment_status_id),
                         CONSTRAINT fk_payments_orders FOREIGN KEY(order_id) REFERENCES orders(order_id),
                         CONSTRAINT ck_positive_amount CHECK ( amount > 0 )
);

CREATE TABLE items(
                      item_code VARCHAR(30),
                      name VARCHAR(30) NOT NULL,
                      brand VARCHAR(30) NOT NULL,
                      price NUMERIC(12,2) NOT NULL,
                      stock_quantity INT NOT NULL,

                      CONSTRAINT pk_item PRIMARY KEY(item_code),
                      CONSTRAINT ck_positive_price CHECK ( price > 0 ),
                      CONSTRAINT ck_non_negative_stock CHECK ( stock_quantity >= 0 ),
                      CONSTRAINT uq_item_name UNIQUE(name,brand)
);

CREATE TABLE order_details(
                              order_detail_id INT GENERATED BY DEFAULT AS IDENTITY,
                              item_code VARCHAR(30) NOT NULL,
                              order_id INT NOT NULL,
                              quantity INT NOT NULL,
                              unit_price NUMERIC(12,2) NOT NULL,
                              CONSTRAINT pk_order_detail PRIMARY KEY(order_detail_id),
                              CONSTRAINT fk_order_details_items FOREIGN KEY(item_code) REFERENCES items(item_code),
                              CONSTRAINT fk_order_details_orders FOREIGN KEY (order_id) REFERENCES orders(order_id)
                                  ON UPDATE CASCADE
                                  ON DELETE CASCADE,
                              CONSTRAINT ck_positive_quantity CHECK ( quantity > 0 ),
                              CONSTRAINT ck_positive_unit_price CHECK ( unit_price > 0 )
);


CREATE INDEX idx_orders_customer        ON orders (customer_id);
CREATE INDEX idx_order_details_order    ON order_details (order_id);
CREATE INDEX idx_order_details_item     ON order_details (item_code);
CREATE INDEX idx_payments_order         ON payments (order_id);
CREATE INDEX idx_history_order_changed  ON order_status_history (order_id, changed_at);

CREATE OR REPLACE FUNCTION fn_sync_order_status()
    RETURNS TRIGGER AS $$
BEGIN
    UPDATE orders
    SET order_status_id = (SELECT h.order_status_id
                           FROM order_status_history h
                           WHERE h.order_id = NEW.order_id
                           ORDER BY h.changed_at DESC, h.history_id DESC
                           LIMIT 1)
    WHERE order_id = NEW.order_id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_history_sync_order_status
    AFTER INSERT ON order_status_history
    FOR EACH ROW EXECUTE FUNCTION fn_sync_order_status();